/** Explicit reviewed source checkout only; no fetch/environment/credential access. */
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { resolve, join } from "node:path";
import { pathToFileURL } from "node:url";
const args = process.argv.slice(2),
  at = args.indexOf("--source");
if (at < 0 || !args[at + 1]) throw Error("--source RHC worktree required");
const root = resolve(args[at + 1]),
  apiPath = "packages/relayhistory/src/lib/search-feature-journal.ts",
  migrationPath =
    "packages/relayhistory/db/migrations/0076_search_feature_journal.sql";
const text = await readFile(join(root, apiPath), "utf8"),
  migration = await readFile(join(root, migrationPath), "utf8");
const sha = (v: string) => createHash("sha256").update(v).digest("hex");
const git = (...a: string[]) =>
  execFileSync("git", ["-C", root, ...a], { encoding: "utf8" });
if (git("status", "--porcelain", "--", apiPath, migrationPath).trim())
  throw Error("source API/migration must be committed");
const target = new URL("../src/search-features/source.ts", import.meta.url),
  authorityTarget = new URL(
    "../src/search-features/source-authority.ts",
    import.meta.url,
  );
let apiCommit = git("log", "-1", "--format=%H", "--", apiPath).trim(),
  migrationCommit = git("log", "-1", "--format=%H", "--", migrationPath).trim();
if (args.includes("--check")) {
  const authority = await readFile(authorityTarget, "utf8");
  const a = /apiCommit: "([0-9a-f]{40})"/.exec(authority),
    m = /migrationCommit: "([0-9a-f]{40})"/.exec(authority);
  if (!a || !m) throw Error("source authority provenance invalid");
  apiCommit = a[1]!;
  migrationCommit = m[1]!;
  // A cherry-pick or unrelated HEAD change is not API drift. Pinned commits must
  // still exist and contain EXACT current reviewed source bytes.
  if (
    git("show", apiCommit + ":" + apiPath) !== text ||
    git("show", migrationCommit + ":" + migrationPath) !== migration
  )
    throw Error("pinned source authority drift");
}
const apiSha256 = sha(text),
  migrationSha256 = sha(migration),
  identitySha256 = sha(JSON.stringify({ apiSha256, migrationSha256 }));
const { buildFeatureSourceAuthority } = await import(
  pathToFileURL(
    join(
      root,
      "packages/relayhistory/scripts/build-feature-source-authority.mjs",
    ),
  ).href
);
const authority = buildFeatureSourceAuthority({
  apiText: text,
  migrationText: migration,
  apiCommit,
  migrationCommit,
});
const expected =
  "// GENERATED from relayhistory-cloud " +
  apiPath +
  "\n// Source commit: " +
  apiCommit +
  "; SHA256: " +
  apiSha256 +
  "\n// Regenerate/check: bun scripts/sync-search-feature-source.ts --source <RHC-worktree> [--check]\n" +
  text;
const expectedAuthority =
  "// GENERATED by scripts/sync-search-feature-source.ts; do not edit.\n// This fingerprints reviewed source bytes; live DB application needs separate verification.\nexport const FEATURE_SOURCE_AUTHORITY = {\n" +
  Object.entries(authority)
    .map(([k, v]) => "  " + k + ": " + JSON.stringify(v) + ",")
    .join("\n") +
  "\n} as const;\n";
if (args.includes("--check")) {
  if (
    (await readFile(target, "utf8")) !== expected ||
    (await readFile(authorityTarget, "utf8")) !== expectedAuthority
  )
    throw Error("generated feature API/authority drift");
} else {
  await writeFile(target, expected);
  await writeFile(authorityTarget, expectedAuthority);
}
console.log(
  JSON.stringify({ ...authority, checked: args.includes("--check") }),
);
