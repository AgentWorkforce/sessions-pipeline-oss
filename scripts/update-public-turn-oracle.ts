/** Generate the parity oracle from the authoritative RHC function used by erasure
 * and matching public selectedSessionTurns. Never queries a database. */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const [checkout, ref, mode] = process.argv.slice(2);
if (
  !checkout ||
  !ref ||
  !/^[0-9a-f]{40}$/u.test(ref) ||
  (mode && mode !== "--check")
)
  throw new Error(
    "usage: update-public-turn-oracle.ts <RHC checkout> <exact SHA> [--check]",
  );
const path =
  "packages/relayhistory/db/migrations/0074_erasure_purges_conversation_turns.sql";
const source = execFileSync("git", ["-C", checkout, "show", ref + ":" + path], {
  encoding: "utf8",
});
const body = source.match(
  /CREATE OR REPLACE FUNCTION sessions\.selected_session_turn_ids\([\s\S]*?\$selected_turns\$;/u,
)?.[0];
if (!body) throw new Error("public selected turns oracle missing");
const output = `-- GENERATED by scripts/update-public-turn-oracle.ts; do not hand-edit.\n-- Source: AgentWorkforce/relayhistory-cloud ${ref}:${path}\n-- Function SHA256: ${createHash("sha256").update(body).digest("hex")}\n${body}\n`;
const target = fileURLToPath(
  new URL(
    "../src/shared/__tests__/fixtures/public-selected-turns.sql",
    import.meta.url,
  ),
);
if (mode === "--check") {
  if (readFileSync(target, "utf8") !== output)
    throw new Error("public turn oracle drift");
} else writeFileSync(target, output);
